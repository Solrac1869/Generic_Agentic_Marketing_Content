#!/usr/bin/env python3
"""render-status.py — turn the last verify run into a readable status page.

docs/STATUS.md is written by a person and holds the things no machine can
know: the order the operator wants gaps closed in, the working agreement, decisions
still open. This writes the other half, the part a machine can assert, so that
nobody has to maintain it by hand and nobody has to trust prose about the state
of a system that can be asked directly.

The two are kept in separate files on purpose. A single file mixing checked
facts with hand-written claims inherits the credibility of the checked half and
the rot of the other, which is exactly how a status page becomes confidently
wrong.

It rewrites the page only when a check's STATUS changes, not when a detail
moves. A token's countdown ticks every day and means nothing new; a token
crossing thirty days does. That way `git diff --quiet` is a sufficient test for
"has anything actually happened", and the commit log carries signal instead of
a daily heartbeat.

    render-status.py [--check]     --check exits 1 if the page is out of date
"""

import datetime
import hashlib
import json
import pathlib
import sys

#: What notifications call this system. Neutral default; set
#: BRAND_LABEL to your own.
import os
_LABEL = os.environ.get("BRAND_LABEL", "Marketing agents")

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
try:
    from agents.verify import OK, WARN, FAIL
except Exception:                                    # standalone, no repo on path
    OK, WARN, FAIL = "ok", "warn", "FAIL"
LATEST = ROOT / "state" / "verify-latest.json"
SIGFILE = ROOT / "state" / "status-render.sig"
PAGE = ROOT / "docs" / "STATUS-generated.md"

# Checks worth surfacing individually even when they pass, because their value
# is the number they carry rather than the fact they are green.
TRACKED = ("token:linkedin", "credentials:rotation", "outputs:url_tagging",
           "cron:verify", "published:passes_current_rules")


def signature(results):
    """What counts as a change.

    Status for every check, because a detail that moves without a status change
    is usually noise: a countdown ticking down a day says nothing new.

    But the tracked checks are surfaced precisely because the number they carry
    is the point, so their detail counts too. Without this the page would keep
    publishing "45 days" a fortnight after it became 31, and someone would plan
    against it.
    """
    pairs = sorted(
        (r.get("check", ""), r.get("status", ""),
         r.get("detail", "") if r.get("check") in TRACKED else "")
        for r in results)
    return hashlib.sha256(json.dumps(pairs).encode()).hexdigest()[:16]


def _table(rows, empty):
    if not rows:
        return [empty, ""]
    out = ["| Check | Detail |", "|---|---|"]
    for r in rows:
        detail = str(r.get("detail", "")).replace("|", "\\|")
        out.append(f"| `{r.get('check','?')}` | {detail} |")
    out.append("")
    return out


def render(data):
    results = data.get("results", [])
    fails = [r for r in results if r.get("status") == FAIL]
    warns = [r for r in results if r.get("status") == WARN]
    oks = [r for r in results if r.get("status") == OK]
    ran = data.get("timestamp", "unknown")

    body = [
        f"# {_LABEL}, checked state",
        "",
        "**Generated by `bin/render-status.py` from the last `verify` run. Do not",
        "edit this file; your changes will be overwritten.** Decisions, the",
        "gap-closing order and the working agreement live in `docs/STATUS.md`,",
        "which is written by hand.",
        "",
        f"Last verify run: **{ran}**. "
        f"{len(results)} checks, {len(oks)} ok, "
        f"{len(warns)} warning(s), {len(fails)} failure(s).",
        "",
        "This page is rewritten only when a check changes status, so an old",
        "timestamp means nothing has moved, not that nobody looked.",
        "",
        "## Failing",
        "",
    ]
    body += _table(fails, "Nothing failing.")
    body += ["## Warning", ""]
    body += _table(warns, "Nothing warning.")

    shown = {r.get("check") for r in fails + warns}
    tracked = [r for r in results
               if r.get("check") in TRACKED and r.get("check") not in shown]
    if tracked:
        body += ["## Tracked facts", "",
                 "Surfaced whatever their status, because the number matters.",
                 ""]
        body += _table(tracked, "")

    body += ["## How to refresh this",
             "",
             "    bin/run-agent.sh verify",
             "",
             "which rewrites `state/verify-latest.json`, then",
             "",
             "    python3 bin/render-status.py",
             "",
             "Both run on the droplet under cron, and `bin/backup.sh` commits this",
             "page when it changes.",
             ""]
    return "\n".join(body)


def main():
    check_only = "--check" in sys.argv
    if not LATEST.exists():
        print(f"no verify results at {LATEST}; run verify first", file=sys.stderr)
        return 1
    try:
        data = json.loads(LATEST.read_text())
    except (ValueError, OSError) as e:
        print(f"cannot read {LATEST}: {type(e).__name__}: {e}", file=sys.stderr)
        return 1

    sig = signature(data.get("results", []))
    prev = SIGFILE.read_text().strip() if SIGFILE.exists() else ""

    # Compare content, not just the signature. If someone edits the page by
    # hand despite the notice at the top, the signature still matches and the
    # edit would survive, then get committed under a message asserting it was
    # machine written. Rendering is cheap; the honest guard is worth it.
    fresh = render(data)
    if sig == prev and PAGE.exists() and PAGE.read_text() == fresh:
        print("status unchanged, page left alone")
        return 0
    if check_only:
        print("status page is out of date")
        return 1

    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text(fresh)
    SIGFILE.parent.mkdir(parents=True, exist_ok=True)
    SIGFILE.write_text(sig)
    print(f"wrote {PAGE.relative_to(ROOT)} ({sig})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
