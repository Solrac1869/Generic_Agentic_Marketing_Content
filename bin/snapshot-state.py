#!/usr/bin/env python3
"""Put the irreplaceable state somewhere other than this droplet.

state/ is gitignored, for a good reason: parts of it change every five minutes
and tracking those would mean a commit storm. But the exclusion was applied to
the whole directory, and some of what lives there cannot be regenerated by
anything:

    performance-arp.json   every observation ever recorded
    crm-arp.json           the contacts and their lifecycle state
    claims-arp.json        the claim pool, including the substantiated ones
    budget-ledger-arp.json what has been spent, and on what

backup.sh pushes git and nothing else, so none of it has ever left the box.
The code was backed up and everything the system had learned was not. Losing
the droplet would have cost the research pool, the contact history and every
performance number, while the thing that was safe -- the code -- is the part
that could most easily be written again.

This copies those files into state-snapshot/, which IS tracked, once a day.
Volatile files are left alone: budgets reset daily, verify-latest is rewritten
every run, run records and logs are noise. JSON diffs and compresses well, so a
daily commit of a slowly-changing file costs very little.

    bin/snapshot-state.py            report what would change
    bin/snapshot-state.py --apply    copy, commit, push
"""

import argparse
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "state"
DEST = ROOT / "state-snapshot"

#: Matched against the filename. Everything else in state/ is regenerable.
DURABLE = ("claims-", "crm-", "performance-", "budget-ledger-")

NOTE = """\
# State snapshot

A daily copy of the files in `state/` that cannot be regenerated: the claim
pool, the contacts, every performance observation, and the spend ledger.

`state/` itself is gitignored because parts of it change every five minutes.
That exclusion covered these too, so until this existed the code was backed up
and everything the system had learned was not.

Written by `bin/snapshot-state.py`, once a day from `bin/backup.sh`. Not read
by anything at runtime — it is a copy, and the live files stay in `state/`.
To restore, copy a file back into `state/` and restart nothing; the agents
read it on their next run.
"""


def _identity():
    """Who commits the snapshot. Neutral unless the brand says otherwise."""
    try:
        sys.path.insert(0, str(ROOT))
        from core import settings, orchestrator
        return settings.commit_identity(
            orchestrator.load_brand(orchestrator.default_brand_id()))
    except Exception:
        return ("Content agent", "agent@localhost")


def durable_files():
    if not SRC.is_dir():
        return []
    return sorted(f for f in SRC.glob("*.json")
                  if any(f.name.startswith(p) for p in DURABLE))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    files = durable_files()
    if not files:
        print("Nothing durable in state/ to snapshot.")
        return 0

    changed, total = [], 0
    for f in files:
        dest = DEST / f.name
        same = dest.exists() and dest.read_bytes() == f.read_bytes()
        total += f.stat().st_size
        if not same:
            changed.append(f.name)
        print("  %-28s %7.0f KB %s"
              % (f.name, f.stat().st_size / 1024, "" if same else "changed"))

    if not changed:
        print("\n%d file(s), %.1f MB, all unchanged since the last snapshot."
              % (len(files), total / 1e6))
        return 0

    print("\n%d of %d file(s) changed, %.1f MB total."
          % (len(changed), len(files), total / 1e6))
    if not args.apply:
        print("Run with --apply to copy, commit and push.")
        return 0

    DEST.mkdir(parents=True, exist_ok=True)
    (DEST / "README.md").write_text(NOTE)
    for f in files:
        shutil.copy2(f, DEST / f.name)

    add = subprocess.run(["git", "-C", str(ROOT), "add", "--", "state-snapshot"],
                         capture_output=True, text=True, timeout=120)
    if add.returncode != 0:
        print("could not stage: %s" % (add.stderr or add.stdout)[:200])
        return 1
    msg = ("state: daily snapshot (%s)\n\n"
           "The files in state/ that cannot be regenerated. state/ is "
           "gitignored; these are copies, so losing the droplet no longer "
           "costs the claim pool, the contacts or the performance history."
           % ", ".join(changed))
    c = subprocess.run(
        ["git", "-C", str(ROOT),
         "-c", "user.name=%s" % _identity()[0],
         "-c", "user.email=%s" % _identity()[1],
         "commit", "-q", "-m", msg], capture_output=True, text=True, timeout=120)
    if c.returncode != 0 and "nothing to commit" not in (c.stdout + c.stderr):
        print("could not commit: %s" % (c.stderr or c.stdout)[:200])
        return 1
    print("Committed. sync-github.sh sends it within fifteen minutes.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
