#!/bin/bash
# Nightly off-machine backup of the marketing agents repo.
#
# The repo had a remote all along, but it was a bare repo on this same droplet:
# real version control, and no protection at all against losing the machine.
# This pushes committed work to GitHub as well.
#
# It deliberately does NOT commit anything. Auto-committing would silence
# verify's uncommitted-changes check, which is a useful signal that code has
# been edited on the box and not recorded. Generated output under brands/
# churns daily and is meant to be committed deliberately, with the code that
# produced it.
set -uo pipefail
cd /root/marketing-agents || exit 1

LOG=/root/marketing-agents/state/backup.log
mkdir -p "$(dirname "$LOG")"
now() { date -u +%FT%TZ; }

# Email, not Telegram. Telegram was retired once the board could take a
# decision rather than only report one. Every alert in this file says the work
# has no off-machine copy, which is the last message that should be delivered
# to a channel nobody reads any more.
alert() {
  set -a; . /etc/marketing-agents.env 2>/dev/null; set +a
  python3 - "$1" <<'PYALERT' 2>/dev/null
import sys
sys.path.insert(0, "/root/marketing-agents")
try:
    from agents.publish import notify
    notify(sys.argv[1], subject="ARP: backup")
except Exception:
    pass
PYALERT
}

# The generated status page is the one path this script commits, and the
# exemption is deliberate rather than a drift from the rule above. It is
# machine output whose whole purpose is to travel to GitHub and the droplet,
# bin/render-status.py rewrites it only when something actually changes so this
# fires rarely rather than nightly, and check_code_drift scopes its dirty
# signal to agents/ core/ bin/, so committing a file under docs/ does not
# silence it.
python3 bin/render-status.py >> "$LOG" 2>&1 || \
  echo "$(now) render-status failed rc=$?" >> "$LOG"

# Compare against HEAD, not the index. `git diff --quiet -- path` compares the
# worktree to the index, so if an add ever succeeded while the commit failed,
# the file would look unchanged from then on and the published page would
# freeze silently and permanently.
if ! git diff --quiet HEAD -- docs/STATUS-generated.md 2>/dev/null \
   || [ -n "$(git ls-files --others --exclude-standard -- docs/STATUS-generated.md)" ]; then
  # The add is needed for the very first commit: --only refuses a pathspec git
  # has never seen. Once the path is in the index, --only commits that path and
  # nothing else, which is the property being bought here.
  git add docs/STATUS-generated.md
  # --only commits this path alone and leaves the rest of the index untouched.
  # A bare commit would sweep up anything staged on the droplet and push it to
  # GitHub unattended: git add -A's failure mode, on a timer.
  if git commit -q --only docs/STATUS-generated.md \
       -m "chore: system status changed

Regenerated by bin/render-status.py because a check changed. Written from
state/verify-latest.json, not by hand." 2>>"$LOG"; then
    echo "$(now) status page committed" >> "$LOG"
  else
    rc=$?
    echo "$(now) status page commit FAILED rc=$rc" >> "$LOG"
    git reset -q -- docs/STATUS-generated.md
  fi
fi

# A deadman for verify. verify cannot detect its own absence: if its cron line
# goes, it simply never runs and never reports. This job runs on its own
# schedule, so it is the right place to notice the silence.
stamp=$(stat -c %Y state/verify-latest.json 2>/dev/null || echo 0)
age_h=$(( ( $(date +%s) - stamp ) / 3600 ))
if [ "$stamp" = "0" ] || [ "$age_h" -gt 36 ]; then
  alert "Marketing agents: verify has not run for ${age_h}h on $(hostname).
The health check is the thing that notices everything else, so this is first."
  echo "$(now) DEADMAN verify stale ${age_h}h" >> "$LOG"
fi

dirty=$(git status --short | wc -l)
ahead=$(git rev-list --count github/main..main 2>/dev/null || echo "?")

out=$(git push github main 2>&1)
rc=$?
echo "$(now) push rc=$rc ahead=$ahead dirty=$dirty ${out//$'\n'/ }" >> "$LOG"

if [ "$rc" -ne 0 ]; then
  alert "Marketing agents: the nightly backup to GitHub FAILED.
$(echo "$out" | tail -3)
The only copies are on this droplet."
  exit 1
fi

# Uncommitted work is not backed up by definition. Say so once a week rather
# than nightly, so it stays a signal rather than noise.
if [ "$dirty" -gt 20 ] && [ "$(date +%u)" = "7" ]; then
  alert "Marketing agents: $dirty uncommitted file(s) on the droplet.
Committed work is backed up to GitHub; these are not."
fi
exit 0
