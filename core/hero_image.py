#!/usr/bin/env python3
"""hero_image.py, branded hero images for blog posts.

Matches the house style used on the blog index: large cream serif title on the
left, a gold supporting line beneath it, the brand mark at the bottom, and a
gold line-art illustration on the right with a few decorative marks.

Programmatic rather than generated by an image model. The result is
deterministic, on brand every time, costs nothing, and cannot invent garbled
text or a wrong logo. It doubles as the OG image, so it is raster rather than
SVG: social platforms will not render SVG.

Needs rsvg-convert and cwebp, both small.
"""

import pathlib, re, subprocess, tempfile

# The palette lives in brand.yaml under art_direction, so the video renderer
# and anything added later share it. These literals remain as a fallback: a
# missing config key must not stop an image being made.
INK, GOLD, CREAM = "#1a2730", "#947f5b", "#f0ece4"


def palette(brand=None):
    """Brand colours, from config where present."""
    a = ((brand or {}).get("art_direction") or {}).get("palette") or {}
    return (a.get("ink", INK), a.get("gold", GOLD), a.get("cream", CREAM))
W, H = 1200, 630
SERIF = "DejaVu Serif, Georgia, 'Times New Roman', serif"
SANS = "DejaVu Sans, Poppins, Arial, sans-serif"

